#!/usr/bin/env node
/**
 * Quota-free redirect sources for javan.de:
 * - Workers Static Assets `_redirects` (path-only, this Worker)
 * - Cloudflare Bulk Redirects (account list; includes www + newsletter aliases)
 *
 * Worker `decide()` stays as fallback for unpublished slugs and ?feed=.
 */
import slugs from "../config/article-slugs.json" with { type: "json" };
import { BLOG_FEED, BLOG_ORIGIN, SHORT_LINKS } from "../src/routing.js";

export const APEX = "https://javan.de";
export const WWW = "https://www.javan.de";
export const UNAGENTIC = "https://unagentic.javan.de";

const FEED_PATHS = [
  "/feed",
  "/feed/",
  "/rss",
  "/rss/",
  "/feed.xml",
  "/atom",
  "/atom/",
  "/comments/feed",
  "/comments/feed/",
];

const ALIAS_HOSTS = ["https://newsletter.javan.de", "https://digest.javan.de"];

function add(map, sourceUrl, targetUrl, extra = {}) {
  if (map.has(sourceUrl)) return;
  map.set(sourceUrl, {
    redirect: {
      source_url: sourceUrl,
      target_url: targetUrl,
      status_code: extra.status_code ?? 301,
      preserve_query_string: extra.preserve_query_string ?? true,
      subpath_matching: extra.subpath_matching ?? false,
      include_subdomains: false,
      preserve_path_suffix: extra.preserve_path_suffix ?? true,
    },
  });
}

function articleTargets() {
  const out = [];
  const seen = new Set();
  for (const slug of slugs) {
    const encoded = encodeURI(slug);
    const target = `${BLOG_ORIGIN}/${encoded}/`;
    for (const pathSlug of new Set([slug, encoded])) {
      const key = `${pathSlug}\0${target}`;
      if (seen.has(key)) continue;
      seen.add(key);
      out.push({ pathSlug, target });
    }
  }
  return out;
}

/** Account Bulk Redirect items (javan.de, www, newsletter/digest aliases). */
export function bulkRedirectItems() {
  const map = new Map();
  const articles = articleTargets();

  for (const host of [APEX, WWW]) {
    for (const { pathSlug, target } of articles) {
      add(map, `${host}/${pathSlug}`, target);
      add(map, `${host}/${pathSlug}/`, target);
    }
    for (const path of FEED_PATHS) {
      add(map, `${host}${path}`, BLOG_FEED);
    }
    for (const [seg, short] of Object.entries(SHORT_LINKS)) {
      add(map, `${host}/${seg}`, short.location, {
        status_code: short.status,
        preserve_query_string: false,
      });
      add(map, `${host}/${seg}/`, short.location, {
        status_code: short.status,
        preserve_query_string: false,
      });
    }
  }

  // Homepage only — do not subpath-match `/api/*` (POST subscribe must stay on-host).
  for (const src of ALIAS_HOSTS) {
    add(map, src, `${UNAGENTIC}/`, { preserve_query_string: true });
    add(map, `${src}/`, `${UNAGENTIC}/`, { preserve_query_string: true });
  }

  return [...map.values()];
}

/** Static Assets `_redirects` (apex paths only; www is a zone Single Redirect). */
export function staticRedirectsFile() {
  const lines = [
    "# Generated by scripts/quota-free-redirects.mjs — do not edit by hand.",
    "# Applied by Workers Static Assets when the Worker does not run first.",
  ];
  for (const { pathSlug, target } of articleTargets()) {
    lines.push(`/${pathSlug} ${target} 301`);
    lines.push(`/${pathSlug}/ ${target} 301`);
  }
  for (const path of FEED_PATHS) {
    lines.push(`${path} ${BLOG_FEED} 301`);
  }
  for (const [seg, short] of Object.entries(SHORT_LINKS)) {
    lines.push(`/${seg} ${short.location} ${short.status}`);
    lines.push(`/${seg}/ ${short.location} ${short.status}`);
  }
  return `${lines.join("\n")}\n`;
}
